export const catalogs: Record<Locale, Record<MessageKey, string>> = { en, ko };

export type Translator = (key: MessageKey, params?: Record<string, string | number>) => string;

export function interpolate(template: string, params?: Record<string, string | number>): string {
  return params ? template.replace(/\{(\w+)\}/g, (_, k: string) => (k in params ? String(params[k]) : `{${k}}`)) : template;
}

export function createTranslator(locale: Locale): Translator {
  const catalog = catalogs[locale];
  return (key, params) => interpolate(catalog[key], params);
}

export const tEn: Translator = createTranslator("en");

/** Plain-language explanation for a failure reason code; unknown codes are shown as-is, never hidden. */
export function reasonText(t: Translator, reason: string): string {
  const key = `reason.${reason}`;
  return key in catalogs.en ? t(key as MessageKey) : t("outcome.stopped", { reason: reason.slice(0, 80) });
}

/** Label for a role reported by the browser's accessibility tree. Unknown roles are shown unchanged. */
export function roleLabel(t: Translator, role: string): string {
  const key = `role.${role}`;
  return key in catalogs.en ? t(key as MessageKey) : role;
}

/** The dashboard's slice of the catalog: its own text plus the vocabulary it displays. */
export function uiMessages(locale: Locale): Record<string, string> {
  return Object.fromEntries(Object.entries(catalogs[locale]).filter(([k]) => /^(ui|kind|role)\./.test(k)));
}
